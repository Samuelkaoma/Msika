// Generates TypeScript types for the Msika API from its OpenAPI description (card M-26).
//
//   node scripts/gen-api.mjs          writes src/api/schema.ts from ../../docs/api/openapi.json
//   node scripts/gen-api.mjs --check  fails if src/api/schema.ts is not what the description gives
//
// The description is generated from msika-api's code and checked by OpenApiSpecTest, so the chain is:
// Java code -> docs/api/openapi.json -> src/api/schema.ts -> the dashboard, each step checked.
//
// It handles the parts of OpenAPI 3.1 that msika-api produces: objects, arrays, enums, string formats, maps
// ($ref, type arrays with "null", oneOf and anyOf too). Anything else becomes `unknown`, never a guess.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const specPath = resolve(here, "../../../docs/api/openapi.json");
const outPath = resolve(here, "../src/api/schema.ts");

const spec = JSON.parse(readFileSync(specPath, "utf8"));

const quote = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name));

function typeOf(schema) {
  if (!schema) return "unknown";
  if (schema.$ref) return schema.$ref.replace("#/components/schemas/", "");
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (schema.oneOf || schema.anyOf) return (schema.oneOf ?? schema.anyOf).map(typeOf).join(" | ");
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  return types
    .map((t) => {
      switch (t) {
        case "string":
          return "string";
        case "integer":
        case "number":
          return "number";
        case "boolean":
          return "boolean";
        case "null":
          return "null";
        case "array":
          return `Array<${typeOf(schema.items)}>`;
        case "object":
          if (schema.properties) return objectType(schema);
          if (schema.additionalProperties) return `Record<string, ${typeOf(schema.additionalProperties)}>`;
          return "Record<string, unknown>";
        default:
          return "unknown";
      }
    })
    .join(" | ");
}

function objectType(schema, indent = "") {
  const required = new Set(schema.required ?? []);
  const lines = Object.keys(schema.properties)
    .sort()
    .map((name) => {
      const prop = schema.properties[name];
      const note = prop.format ? ` // ${prop.format}` : "";
      return `${indent}  ${quote(name)}${required.has(name) ? "" : "?"}: ${typeOf(prop)};${note}`;
    });
  return `{\n${lines.join("\n")}\n${indent}}`;
}

const out = [];
out.push("// Generated by scripts/gen-api.mjs from docs/api/openapi.json. Do not edit by hand:");
out.push("// change the Java code, regenerate the description (see OpenApiSpecTest), then `pnpm --filter council-web gen:api`.");
out.push("");

const schemas = spec.components?.schemas ?? {};
for (const name of Object.keys(schemas).sort()) {
  const s = schemas[name];
  if (s.type === "object" && s.properties) {
    out.push(`export interface ${name} ${objectType(s)}`);
  } else {
    out.push(`export type ${name} = ${typeOf(s)};`);
  }
  out.push("");
}

const methods = ["get", "post", "put", "delete", "patch"];
const bodyOf = (content) => {
  if (!content) return "void";
  const media = content["application/json"] ?? content["*/*"] ?? Object.values(content)[0];
  return media?.schema ? typeOf(media.schema) : "unknown";
};

out.push("/** Every endpoint: its path parameters, query parameters, request body and successful response. */");
out.push("export interface Paths {");
for (const path of Object.keys(spec.paths).sort()) {
  out.push(`  ${JSON.stringify(path)}: {`);
  for (const method of methods) {
    const op = spec.paths[path][method];
    if (!op) continue;
    const params = op.parameters ?? [];
    const group = (where) => {
      const ps = params.filter((p) => p.in === where);
      if (ps.length === 0) return "never";
      return `{ ${ps.map((p) => `${quote(p.name)}${p.required ? "" : "?"}: ${typeOf(p.schema)}`).join("; ")} }`;
    };
    const ok = Object.keys(op.responses ?? {}).find((code) => code.startsWith("2"));
    out.push(`    ${method}: {`);
    out.push(`      path: ${group("path")};`);
    out.push(`      query: ${group("query")};`);
    out.push(`      body: ${op.requestBody ? bodyOf(op.requestBody.content) : "never"};`);
    out.push(`      response: ${ok ? bodyOf(op.responses[ok].content) : "void"};`);
    out.push("    };");
  }
  out.push("  };");
}
out.push("}");
out.push("");

const text = out.join("\n");
if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error("src/api/schema.ts is out of date with docs/api/openapi.json: run pnpm --filter council-web gen:api");
    process.exit(1);
  }
} else {
  writeFileSync(outPath, text);
  console.log(`wrote ${outPath}`);
}
